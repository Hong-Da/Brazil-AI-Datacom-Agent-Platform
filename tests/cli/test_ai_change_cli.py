"""变更与割接组 AI skill 的命令行连续操作（M8-4）：回放运行 → 采纳 → 查看由代码生成的结果（变更脚本、割接方案、
带 AI 写法的译文、规则集、我的模板）→ 撤销。AI 未配置，回复用 tests/inputs/ai-change/ 回放（同样经过代码校验）。"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from tests.conftest import INPUTS, prepare, run_cli

pytestmark = pytest.mark.cli
BASE = ["--output", "json", "--project", "alice/lab"]
SUG = [*BASE, "ai", "suggest"]
TO = "cisco-iosxe-asr920-17.15"
DEV = "ATN-CHANGE-01"


def _ok(args: list[str], root: Path) -> Any:
    r = run_cli(args, root)
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout)["data"]


def _run(root: Path, skill: str, reply: str, params: dict[str, Any], device: str | None = DEV) -> Any:
    args = [*SUG, "run", skill, "--replay", str(INPUTS / "ai-change" / reply), "--params", json.dumps(params)]
    if device:
        args += ["--device", device]
    return _ok(args, root)


def test_intent_script_adopt_plan_revert(tmp_root: Path, request: pytest.FixtureRequest) -> None:
    prepare("configured-fullkb-suggest", request)
    b = _run(tmp_root, "intent-script", "intent-desc.json", {"intent": "Set the description of GigabitEthernet0/2/2"})
    it = b["items"][0]
    assert it["check_status"] == "pass" and it["refs"][0]["label"] == "GigabitEthernet0/2/2", it
    bid = b["batch"]["id"]
    assert _ok([*BASE, "ai", "change-plan", str(bid)], tmp_root)["adopted"] == []
    a = _ok([*SUG, "adopt", str(it["id"])], tmp_root)["items"][0]
    assert a["adopt_info"]["action"] == "script"
    p = _ok([*BASE, "ai", "change-plan", str(bid)], tmp_root)
    assert p["verify"] and any(r["k"] == "ai" and "description OAM-UPLINK" in r["text"] for r in p["rows"])
    txt = run_cli(["--lang", "en", "--project", "alice/lab", "ai", "change-plan", str(bid)], tmp_root)
    assert txt.returncode == 0 and "+   description OAM-UPLINK" in txt.stdout
    assert _ok([*SUG, "revert", str(it["id"])], tmp_root)["items"][0]["revert_info"]["action"] == "script_deleted"
    bad = _run(tmp_root, "intent-script", "intent-invented.json", {"intent": "Bind GigabitEthernet0/2/2"})
    codes = {r["code"] for r in bad["items"][0]["check"]["reasons"]}
    assert bad["items"][0]["check_status"] == "reject" and "ref_not_found" in codes


def test_cutover_plan_export(tmp_root: Path, request: pytest.FixtureRequest) -> None:
    prepare("configured-fullkb-suggest", request)
    b = _run(tmp_root, "cutover-plan", "cutover-overview.json", {"to": TO})
    ov, rb = sorted(b["items"], key=lambda x: x["id"])
    assert ov["check_status"] == "pass" and rb["check_status"] == "reject"
    assert "command_in_text" in {r["code"] for r in rb["check"]["reasons"]}
    _ok([*SUG, "adopt", str(ov["id"])], tmp_root)
    out = tmp_root / "plan-en.md"
    _ok([*BASE, "ai", "cutover-doc", str(b["batch"]["id"]), "--lang", "en", "--out", str(out)], tmp_root)
    md = out.read_text(encoding="utf-8")
    assert md.startswith("# Cutover plan: replace ATN-CHANGE-01") and "This cutover replaces ATN-CHANGE-01" in md
    assert "reset bgp all" not in md and "## Step list (generated by code)" in md


def test_translate_gap_patch_in_translation(tmp_root: Path, request: pytest.FixtureRequest) -> None:
    prepare("configured-fullkb-suggest", request)
    b = _run(tmp_root, "translate-gap", "translate-gap.json", {"to": TO})
    none_, eq = sorted(b["items"], key=lambda x: x["id"])
    assert none_["check_status"] == "pass" and eq["check_status"] == "warn"
    for it in (none_, eq):
        _ok([*SUG, "adopt", str(it["id"])], tmp_root)
    r = _ok([*BASE, "translate", DEV, "--to", TO], tmp_root)
    lines = r["text"].splitlines()
    assert [lines[n - 1] for n in r["ai_lines"]] == [
        "router bgp 65000",
        " neighbor RR peer-group",
        " neighbor RR remote-as 65000",
    ]
    assert lines[-1] == "end" and {p["line"] for p in r["ai_patches"]} == {4, 68}


def test_naming_and_template_assets(tmp_root: Path, request: pytest.FixtureRequest) -> None:
    prepare("configured-fullkb-suggest", request)
    b = _run(tmp_root, "naming-map", "naming-vrf.json", {"to": TO})
    ok, clash = sorted(b["items"], key=lambda x: x["id"])
    assert ok["check_status"] == "pass" and clash["check"]["reasons"][0]["code"] == "naming_conflict"
    rid = _ok([*SUG, "adopt", str(ok["id"])], tmp_root)["items"][0]["adopt_info"]["id"]
    assert (tmp_root / "data" / "translate-rules" / f"{rid}.yaml").is_file()
    args = [
        *SUG,
        "run",
        "template-extract",
        "--devices",
        DEV,
        "--replay",
        str(INPUTS / "ai-change" / "template-loopback.json"),
    ]
    good, hard = sorted(_ok(args, tmp_root)["items"], key=lambda x: x["id"])
    assert good["check_status"] == "pass", good["check"]
    assert hard["check_status"] == "reject"
    tid = _ok([*SUG, "adopt", str(good["id"])], tmp_root)["items"][0]["adopt_info"]["id"]
    assert (tmp_root / "data" / "user-templates" / f"{tid}.yaml").is_file()
    _ok([*SUG, "revert", str(good["id"])], tmp_root)
    assert not (tmp_root / "data" / "user-templates" / f"{tid}.yaml").exists()
    r = run_cli(
        [*SUG, "run", "template-extract", "--replay", str(INPUTS / "ai-change" / "template-loopback.json")], tmp_root
    )
    assert r.returncode == 2  # 没给设备：参数错误
