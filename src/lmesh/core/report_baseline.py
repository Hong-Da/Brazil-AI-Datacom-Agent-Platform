_MARK = {"pass": "✓", "fail": "✗", "na": "—"}


class _BaselineDoc(_Doc):
    def t(self, key: str, **kw: Any) -> str:
        text = TEXTS[self.lang].get(key) or report.TEXTS[self.lang].get(key, key)
        return text.format(**kw) if kw else text

    def render(self, title: str) -> str:
        out = super().render(title)
        if self.fmt == "html":  # 页脚换成基线报告的说明
            out = out.replace(html.escape(report.TEXTS[self.lang]["footer"]), html.escape(self.t("baseline.footer")))
        return out


def _score(v: Any) -> str:
    return "—" if v is None else str(v)


def baseline_report(
    result: dict[str, Any],
    lang: str,
    fmt: str,
    now: datetime | None = None,
    namer: Namer | None = None,
    kb_version: str | None = None,
    ai: dict[str, Any] | None = None,
) -> Report:
    """result 是 baseline.audit 的结果；ai 是已采纳的 AI 摘要（ai_report_summary.for_export，可省）。"""
    report._check_args(lang, fmt)
    doc = _BaselineDoc(fmt, lang, namer)
    texts = result.get("texts") or {}
    info = result.get("baseline_info") or {}
    s = result["summary"]
    title = doc.t("baseline.title")
    doc.h(1, title)
    doc.p(f"{doc.t('generated')}: {_now(now)}", "note")
    prof_title = (info.get("title") or {}).get(lang) or result.get("baseline")
    chain = [c for c in info.get("chain") or [] if c != result.get("baseline")]
    rows = [
        [doc.esc(doc.t("baseline.profile")), doc.esc(f"{prof_title} ({result.get('baseline')})")],
        [doc.esc(doc.t("baseline.chain")), doc.esc(", ".join(chain) or doc.t("none"))],
        [doc.esc(doc.t("baseline.devices")), doc.esc(s["devices"])],
        [doc.esc(doc.t("baseline.rules")), doc.esc(s["rules"])],
    ]
    if kb_version:
        rows.append([doc.esc(doc.t("kb_version")), doc.esc(kb_version)])
    doc.table([doc.t("item"), doc.t("value")], rows, "meta")
    report.ai_section(doc, ai)
    desc = (info.get("description") or {}).get(lang)
    if desc:
        doc.p(desc, "note")

    doc.section("summary")
    doc.h(2, doc.t("summary"))
    _stats(
        doc,
        [
            (doc.t("baseline.overall"), _score(s["score"])),
            (doc.t("baseline.pass"), s["pass"]),
            (doc.t("baseline.fail"), s["fail"]),
            (doc.t("baseline.na"), s["na"]),
            (doc.t("baseline.failures"), s["failures"]),
        ],
    )
    doc.p(doc.t("baseline.weight_note"), "note")
    doc.end()

    # 矩阵：行是规则，列是设备
    devices = result["devices"]
    doc.section("matrix")
    doc.h(2, doc.t("baseline.matrix"))
    doc.p(doc.t("baseline.matrix_note"), "note")
    header = [doc.t("rule"), doc.t("severity")] + [str(d["device"]) for d in devices]
    mrows: list[list[str]] = []
    classes: list[str] = []
    for r in result["rules"]:
        name = (r["title"] or {}).get(lang) or r["id"]
        cells = [_MARK[d["results"][r["id"]]] for d in devices]
        mrows.append([f"{doc.code(r['id'])} {doc.esc(name)}", doc.esc(doc.t(f"severity.{r['severity']}"))] + cells)
        classes.append(f"s-{r['severity']}")
    mrows.append(
        [doc.esc(doc.t("baseline.score")), ""] + [doc.esc(_score(d["score"])) for d in devices],
    )
    classes.append("")
    doc.table(header, mrows, "matrix", classes)
    doc.end()

    # 每台设备的不符合项
    fheader = [
        doc.t("severity"),
        doc.t("rule"),
        doc.t("node"),
        doc.t("line"),
        doc.t("message"),
        doc.t("suggestion"),
        doc.t("baseline.remedy"),
    ]
    for d in devices:
        doc.section("device")
        doc.h(2, doc.t("baseline.device_section", device=d["device"], family=d.get("family") or "-"))
        sm = d["summary"]
        doc.p(
            doc.t("baseline.device_score", score=_score(d["score"]), **{k: sm[k] for k in blmod.STATUSES}),
        )
        if not d["failures"]:
            doc.p(doc.t("baseline.all_pass"), "ok")
            doc.end()
            continue
        frows: list[list[str]] = []
        fcls: list[str] = []
        for f in d["failures"]:
            badge = doc.t(f"severity.{f['severity']}")
            sev = f'<span class="badge">{html.escape(badge)}</span>' if fmt == "html" else badge
            cmd = "<br>".join(doc.code(c) for c in f["remedy"])  # Markdown 表格里同样用 <br> 换行
            frows.append(
                [
                    sev,
                    doc.code(f["rule"]),
                    doc.node(f["node"]) if f["node"] != "device" else doc.esc(doc.t("device")),
                    doc.esc(_lines_text(f["lines"], 12)),
                    doc.esc(blmod.render_text(f["message"], lang, texts)),
                    doc.esc(blmod.render_text(f["suggestion"], lang, texts)),
                    cmd,
                ]
            )
            fcls.append(f"s-{f['severity']}")
        doc.table(fheader, frows, "findings", fcls)
        doc.end()
    if any(d["failures"] for d in devices):
        doc.p(doc.t("baseline.remedy_note"), "note")

    doc.section("rules")
    doc.h(2, doc.t("baseline.rule_list"))
    doc.table(
        [doc.t("rule"), doc.t("severity"), doc.t("baseline.title_col"), doc.t("suggestion")],
        [
            [
                doc.code(r["id"]),
                doc.esc(doc.t(f"severity.{r['severity']}")),
                doc.esc((r["title"] or {}).get(lang, "")),
                doc.esc((r["suggestion"] or {}).get(lang, "")),
            ]
            for r in result["rules"]
        ],
    )
    doc.end()
    name = devices[0]["device"] if len(devices) == 1 else f"{len(devices)}-devices"
    filename = f"baseline-{result.get('baseline')}-{_safe(name)}.{lang}.{fmt}"
    report.ai_note(doc, ai)
    return Report(filename, doc.render(title), report._media(fmt))
