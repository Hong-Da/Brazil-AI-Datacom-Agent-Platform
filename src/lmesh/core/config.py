class ConfigError(ValueError):
    """配置值不合法。"""


def config_path() -> Path:
    override = os.environ.get("LMESH_CONFIG_FILE")  # CLI 的 --config
    return Path(override) if override else paths.config_dir() / "config.toml"


def is_configured() -> bool:
    return config_path().exists()


# ---------- 校验 ----------


def _validate_host(v: str) -> str:
    try:
        ipaddress.ip_address(v)
    except ValueError as e:
        raise ConfigError("host") from e
    return v


def validate(key: str, value: Any) -> Any:
    """校验并转换单个配置值；不合格时抛出 ConfigError（消息为文案键）。"""
    f = FIELD_MAP[key]
    if f.kind in ("int", "port"):
        try:
            value = int(value)
        except (TypeError, ValueError) as e:
            raise ConfigError("int") from e
        if (f.minimum is not None and value < f.minimum) or (f.maximum is not None and value > f.maximum):
            raise ConfigError("range")
        return value
    value = "" if value is None else str(value).strip()
    if f.kind == "choice" and value not in f.choices:
        raise ConfigError("choice")
    if f.kind == "host":
        return _validate_host(value)
    if f.kind == "dburl" and value and not value.startswith(("sqlite", "postgresql")):
        raise ConfigError("dburl")
    if f.kind == "path" and value and Path(value).is_absolute():
        # 运行时目录必须在项目内，相对路径以项目根目录为基准
        try:
            Path(value).resolve().relative_to(paths.project_root())
        except ValueError as e:
            raise ConfigError("path") from e
    return value


# ---------- 读取 ----------


def _get_nested(data: dict[str, Any], key: str) -> Any:
    cur: Any = data
    for part in key.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return None
        cur = cur[part]
    return cur


def _set_nested(data: dict[str, Any], key: str, value: Any) -> None:
    group, name = key.split(".", 1)
    data.setdefault(group, {})[name] = value


@dataclass
class Settings:
    values: dict[str, Any] = field(default_factory=dict)
    sources: dict[str, str] = field(default_factory=dict)  # default / file / env

    def get(self, key: str) -> Any:
        return self.values[key]

    @property
    def database_url(self) -> str:
        url = self.values["database.url"]
        if url:
            return str(url)
        return f"sqlite:///{(paths.data_dir() / 'lmesh.db').as_posix()}"

    @property
    def knowledge_dir(self) -> Path:
        p = Path(self.values["knowledge.dir"])
        return p if p.is_absolute() else paths.project_root() / p

    def ai_api_key(self) -> str:
        return decrypt_secret(str(self.values.get("ai.api_key") or ""))

    def public_dict(self) -> dict[str, Any]:
        """可以展示的配置：敏感值只显示是否已设置。"""
        out: dict[str, Any] = {}
        for f in FIELDS:
            v = self.values[f.key]
            out[f.key] = bool(v) if f.secret else v
        return out


def env_name(key: str) -> str:
    group, name = key.split(".", 1)
    return f"LMESH_{group.upper()}__{name.upper()}"


def load(path: Path | None = None) -> Settings:
    path = path or config_path()
    file_data: dict[str, Any] = {}
    if path.exists():
        with path.open("rb") as fh:
            file_data = tomllib.load(fh)
    s = Settings()
    for f in FIELDS:
        value, source = f.default, "default"
        fv = _get_nested(file_data, f.key)
        if fv is not None:
            value, source = fv, "file"
        ev = os.environ.get(env_name(f.key))
        if ev is not None:
            value, source = ev, "env"
        try:
            value = validate(f.key, value)
        except ConfigError:
            # 配置文件中的错误值不让程序起不来：回退到默认值，由调用方提示
            value, source = f.default, "default(invalid)"
        s.values[f.key] = value
        s.sources[f.key] = source
    return s


# ---------- 写入 ----------


def _comment(f: Field, lang: str) -> str:
    text = f.desc.get(lang) or f.desc["zh-CN"]
    extra = ""
    if f.choices:
        extra = "  可选：" if lang == "zh-CN" else ("  Options: " if lang == "en" else "  Opções: ")
        extra += " / ".join(c or '""' for c in f.choices)
    return f"# {text}{extra}"


def render_toml(values: dict[str, Any], lang: str = "zh-CN", header: str = "") -> str:
    """生成带注释的 TOML 文本（分组顺序与 FIELDS 一致）。"""
    lines: list[str] = []
    if header:
        lines += [f"# {h}" if h else "#" for h in header.splitlines()] + [""]
    current = None
    for f in FIELDS:
        group, name = f.key.split(".", 1)
        if group != current:
            if current is not None:
                lines.append("")
            title = GROUP_TITLES.get(f.group, {}).get(lang, group)
            lines += [f"# ---- {title} ----", f"[{group}]"]
            current = group
        lines.append(_comment(f, lang))
        frag = tomli_w.dumps({name: values.get(f.key, f.default)}).strip()
        lines.append(frag)
    return "\n".join(lines) + "\n"


def write(values: dict[str, Any], lang: str = "zh-CN", path: Path | None = None) -> Path:
    path = path or config_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    clean = {f.key: validate(f.key, values.get(f.key, f.default)) for f in FIELDS}
    header = {
        "zh-CN": "透网 LucidMesh 配置文件（由首次运行向导生成，可直接编辑）\n环境变量优先：例如 LMESH_SERVER__PORT=9001",
        "en": "LucidMesh configuration (generated by the setup wizard; safe to edit)\nEnvironment variables win, e.g. LMESH_SERVER__PORT=9001",
        "pt-BR": "Configuração do LucidMesh (gerada pelo assistente; pode ser editada)\nVariáveis de ambiente têm prioridade, ex.: LMESH_SERVER__PORT=9001",
    }[lang if lang in LANGS else "zh-CN"]
    path.write_text(render_toml(clean, lang, header), encoding="utf-8")
    return path


def example_text() -> str:
    """config/config.example.toml 的内容。"""
    return render_toml(
        {f.key: f.default for f in FIELDS},
        "zh-CN",
        "透网 LucidMesh 配置示例：复制为 config.toml 后修改，或运行 start 脚本通过向导生成\n"
        "环境变量优先：LMESH_<分组>__<名称>，例如 LMESH_SERVER__PORT=9001",
    )


def new_token() -> str:
    return secrets.token_urlsafe(32)


# ---------- API Key 加密 ----------


def _fernet() -> Any:
    from cryptography.fernet import Fernet

    key_file = paths.config_dir() / "secret.key"
    if not key_file.exists():
        key_file.parent.mkdir(parents=True, exist_ok=True)
        key_file.write_bytes(Fernet.generate_key())
    return Fernet(key_file.read_bytes())


def encrypt_secret(plain: str) -> str:
    if not plain or plain.startswith(SECRET_PREFIX):
        return plain
    return SECRET_PREFIX + _fernet().encrypt(plain.encode("utf-8")).decode("ascii")


def decrypt_secret(stored: str) -> str:
    if not stored.startswith(SECRET_PREFIX):
        return stored
    return str(_fernet().decrypt(stored[len(SECRET_PREFIX) :].encode("ascii")).decode("utf-8"))
